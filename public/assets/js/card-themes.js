export function getCardTheme(card_key){
  const k = String(card_key || '').trim();
  return CARD_THEMES[k] || null;
}

export function getSeqStepConfig(card_key, stepIndex, language, gender){
  const theme = getCardTheme(card_key);
  if (!theme || theme.messageMode !== 'sequential') return null;

  const lang      = (language || theme.defaultLanguage || 'en').toLowerCase();
  const msgs      = (theme.stepMessages && (theme.stepMessages[lang] || theme.stepMessages['en'])) || [];
  const steps     = theme.steps || [];

  const msgEntry  = msgs[stepIndex]  || {};
  const stepEntry = steps[stepIndex] || {};

  // Resolve underlayImageSrc (may be object keyed by gender)
  let underlayImageSrc = null;
  if (stepEntry.underlayImageSrc){
    underlayImageSrc = (typeof stepEntry.underlayImageSrc === 'object')
      ? (stepEntry.underlayImageSrc[gender] || null)
      : stepEntry.underlayImageSrc;
  }

  // Resolve bgFloodSrc to { desktop, mobile } using gender
  let bgFloodSrc = null;
  if (stepEntry.bgFloodSrc){
    const entry = stepEntry.bgFloodSrc[gender] || stepEntry.bgFloodSrc;
    if (entry && (entry.desktop || entry.mobile)){
      bgFloodSrc = entry;
    }
  }

  // Resolve revealText from stepMessages (may be object keyed by gender)
  let revealText = null;
  if (msgEntry.revealText){
    revealText = (typeof msgEntry.revealText === 'object')
      ? (msgEntry.revealText[gender] || null)
      : msgEntry.revealText;
  }

  // Resolve stepPageBg and accentColor (may be objects keyed by gender)
  const _resolveGender = (val) =>
    val ? ((typeof val === 'object') ? (val[gender] || null) : val) : null;

  return {
    title:            msgEntry.title  || '',
    titleRevealed:    _resolveGender(msgEntry.titleRevealed),
    underText:        msgEntry.underText ?? null,
    bgDesktopSrc:     stepEntry.bgDesktopSrc || '',
    bgMobileSrc:      stepEntry.bgMobileSrc  || stepEntry.bgDesktopSrc || '',
    cloudsRight1Src: stepEntry.cloudsRight1Src || null,
    cloudsRight2Src: stepEntry.cloudsRight2Src || null,
    cloudsLeftSrc:   stepEntry.cloudsLeftSrc   || null,
    underlayImageSrc,
    shareImageSrc:   _resolveGender(stepEntry.shareImageSrc),
    applyHeartMaskToUnderlay: stepEntry.applyHeartMaskToUnderlay ?? true,
    bgFloodSrc,
    showCustomMessage: !!stepEntry.showCustomMessage,
    revealText,
    shareFraming:  _resolveGender(msgEntry.shareFraming),
    floodPageBg:  _resolveGender(stepEntry.floodPageBg),
    accentColor:  _resolveGender(stepEntry.accentColor),
  };
}

